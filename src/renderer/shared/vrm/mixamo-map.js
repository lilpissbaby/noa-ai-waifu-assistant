// «mixamorig:Hips», «mixamorig1:Hips» o «mixamorigHips» -> «mixamorigHips».
export const mixamoKey = (name) => String(name).replace(/^mixamorig\d*:?/, 'mixamorig');

// boneNames: nombres de los nodos del FBX. Devuelve el mapa nombre del FBX -> hueso VRM, si se
// reconoce como esqueleto de Mixamo (cadera + al menos 10 huesos) y qué huesos VRM faltan.
export function mixamoBoneMap(boneNames) {
  const map = new Map();
  const found = new Set();
  for (const n of boneNames) {
    const bone = MIXAMO_VRM_RIG_MAP[mixamoKey(n)];
    if (bone && !found.has(bone)) {
      map.set(n, bone);
      found.add(bone);
    }
  }
  const missing = Object.values(MIXAMO_VRM_RIG_MAP).filter((b) => !found.has(b));
  return { map, missing, recognized: found.has('hips') && found.size >= 10 };
}
